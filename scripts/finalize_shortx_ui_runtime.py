def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = []

    package_expected = build_package()
    if write_or_check(OUTPUT, package_expected, args.check):
        changed.append(str(OUTPUT.relative_to(ROOT)))

    targets = [
        (ENTRY, patch_entry(read_text(ENTRY))),
        (MANIFEST_GENERATOR, patch_manifest_generator(read_text(MANIFEST_GENERATOR))),
        (PREPARE_CONSTRAINTS, patch_prepare_constraints(read_text(PREPARE_CONSTRAINTS))),
        (API_RULES, patch_api_rules(read_text(API_RULES))),
        (BOUNDARIES, patch_boundaries(read_text(BOUNDARIES))),
        (PROTECTED_REPORTER, patch_protected_reporter(read_text(PROTECTED_REPORTER))),
        (ARCHITECTURE, patch_architecture(read_text(ARCHITECTURE))),
        (STRUCTURE, patch_structure(read_text(STRUCTURE))),
        (LEGACY_FINAL_ENTRY, patch_legacy_final_entry(read_text(LEGACY_FINAL_ENTRY))),
        (VERIFY_WORKFLOW, patch_verify_workflow(read_text(VERIFY_WORKFLOW))),
        (SIGN_WORKFLOW, patch_sign_workflow(read_text(SIGN_WORKFLOW))),
        (SCRIPTS_README, patch_scripts_readme(read_text(SCRIPTS_README))),
    ]
    for path, expected in targets:
        if write_or_check(path, expected, args.check):
            changed.append(str(path.relative_to(ROOT)))

    if args.check:
        print("ShortXUI final package is current")
    elif changed:
        print("Updated ShortXUI final package:")
        for item in changed:
            print(" - " + item)
    else:
        print("ShortXUI final package already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
