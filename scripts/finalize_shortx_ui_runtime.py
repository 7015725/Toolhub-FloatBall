def patch_scripts_readme(text: str) -> str:
    if "- `finalize_shortx_ui_runtime.py`" not in text:
        anchor = "- `generate_signed_manifest.py`\n"
        text = replace_once(
            text,
            anchor,
            anchor + "- `finalize_shortx_ui_runtime.py`：将已验收的 ShortXUI Phase 2 至 Final R3 链生成单一签名模块，并同步入口、约束和文档。\n",
            "scripts README finalizer",
        )
    return text


